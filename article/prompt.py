from user_config import (
    NOTE_CONCEPT,
    ARTICLE_MIN_LENGTH,
    ARTICLE_TARGET_LENGTH,
    ARTICLE_MAX_LENGTH,
)


def get_article_prompt(
    theme,
    angle,
    knowledge,
    past_articles_text,
    current_date,
):
    return f"""
あなたはnote記事の専門ライターです。

現在の日付：
{current_date}

【noteのコンセプト】
{NOTE_CONCEPT}

【今回のテーマ】
{theme}

【今回の切り口】
{angle}

【記事の文字数】
最低文字数：{ARTICLE_MIN_LENGTH}文字
目標文字数：{ARTICLE_TARGET_LENGTH}文字
最大文字数：{ARTICLE_MAX_LENGTH}文字

【記事の目的】

読者がテーマについて理解するだけでなく、
実際に行動へ移せる記事を作成してください。

テーマと切り口を記事全体の中心にしてください。

初心者にも理解できるように、
専門用語は必要に応じて説明してください。

抽象的な説明だけで終わらせず、
具体例、手順、考え方、注意点などを適切に含めてください。

【AI知識】

以下の情報を記事作成時の参考情報として使用してください。

{knowledge}

重要：
- AIサービスの名称、機能、料金、仕様などは提供された知識を優先する
- 古い情報を現在の情報として扱わない
- 知識に存在しない情報を事実として作らない
- AI知識DBについて記事内で言及しない

【過去記事】

以下は過去に生成した記事です。

{past_articles_text}

過去記事と内容・構成・切り口が大きく重複しないようにしてください。

【記事作成ルール】

- Markdown形式
- noteで読みやすい構成
- タイトルを最初に出力
- タイトルは40文字以内を目安とする
- タイトルにはテーマと切り口の内容が伝わる要素を含める
- H2、H3を適切に使用する
- Markdownの表は使用しない
- 項目と説明を「：」で1行にまとめず、項目の下に説明を書く
- 同じ項目に説明が1つしかない場合でも、読みやすさを優先して改行する
- 箇条書きを適切に使用する
- 読者が実際に使える具体的な内容を含める
- 根拠のない体験談を書かない
- 架空の実績、成果、口コミ、利用者の声を書かない
- 「必ず稼げる」「必ず成功する」などの断定を避ける
- 内容を不必要に水増ししない
- 最低文字数を満たすためだけの冗長な文章を書かない
- ハッシュタグは記事の最後にまとめて記載する
- ハッシュタグは1行に複数記載する
- ハッシュタグは「#」の直後に文字を続け、見出し形式（# 見出し）のMarkdownにならないようにする
- ハッシュタグの前にMarkdownの見出し記号（#）を単独で使用しない

【構成】

以下を基本構成として、テーマと切り口に合わせて最適化してください。

1. タイトル
2. 導入
3. テーマと切り口の基本説明
4. 具体的な解説
5. 実践方法・手順
6. 注意点・失敗例
7. まとめ
8. ハッシュタグ
   記事の最後に、例として「#ChatGPT #AI活用 #仕事効率化」のように記載する

ただし、内容に応じて見出し構成は変更して構いません。

【最重要】

今回の記事の中心は、

テーマ：
{theme}

切り口：
{angle}

です。

この2つから外れた内容を記事の中心にしないでください。

完成したnote記事のみを出力してください。
"""